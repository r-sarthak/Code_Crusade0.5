

int_var = int(input("Enter an integer value: "))  # input takes the value as 'string' by default, int() converts it to an integer
float_var = float(input("Enter a float value: "))  # input takes the value as 'string' by default, float() converts it to a float
string_var = input("Enter a string value: ")  # input takes the value as 'string' by default
print("You entered the integer:", int_var)
print("You entered the float:", float_var)
print("You entered the string:", string_var)